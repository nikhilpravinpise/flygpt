"""T-CORPUS-1..7 - dataset integrity runners (EVAL.md sections 1.8, 3, 5).

Corpus layout coded against the impl-spec shard contract: per shard a
``<shard>.events.parquet`` (EVENT_COLUMNS, sorted by trial,step,node), a
``<shard>.trials.parquet`` (TRIAL_COLUMNS), and a ``<shard>.manifest.json``
recording code/git_sha, graph sha256, per-file sha256, dt, slice, split,
backend, gpu_class and counts. A corpus-level ``corpus.manifest.json``
carries the types denominator + the splits block regenerated by
T-CORPUS-4.

Every runner tolerates a missing optional dep via a documented skip
(``checks.skipped`` + ``pass: null``), never a silent pass, and writes
``results/T-CORPUS-*.json`` via ``flygpt.schema.write_result``.
"""


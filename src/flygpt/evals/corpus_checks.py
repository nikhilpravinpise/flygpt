def _trials_table(corpus_dir: Path) -> pl.DataFrame:
    frames = []
    for s in _shard_files(corpus_dir):
        if s["trials"].exists():
            frames.append(pl.read_parquet(s["trials"]))
    return pl.concat(frames) if frames else pl.DataFrame()


def _drive_nodes_of(program: Any) -> list[int]:
    """Primary-stimulated node list from a trial's program spec."""
    spec = json.loads(program) if isinstance(program, str) else (program or {})
    nodes: list[int] = []
    for drive in spec.get("drives") or []:
        nodes.extend(int(n) for n in drive.get("nodes") or [])
    return nodes


_SPLIT_AXES = ("stimulus_holdout", "celltype_holdout", "region_holdout")
# Membership key inside a nested axis block (corpus.build_splits format).
_AXIS_MEMBERS = {
    "stimulus_holdout": ("families", "stimulus_holdout", "family_holdout"),
    "celltype_holdout": ("types", "celltype_holdout", "type_holdout", "celltype"),
    "region_holdout": ("regions", "region_holdout", "region"),
}


def _axis_members(block: dict | None, axis: str) -> list[str]:
    """Recorded holdout membership for one axis - flat list or nested block."""
    if not isinstance(block, dict):
        return []
    v = block.get(axis)
    if isinstance(v, dict):
        for k in (*_AXIS_MEMBERS[axis], "members", "list", "values"):
            if v.get(k) is not None:
                return [str(x) for x in v[k]]
        return []
    if v is None:
        return []
    return [str(x) for x in v]


def run_t_corpus_4(
    corpus_dir: Path,
    results_dir: Path,
    *,
    corpus_manifest: Path | None = None,
    split_fn: Callable | None = None,
    node_type: Any = None,
    node_region: Any = None,
    bundle=None,
    family_ids: list[str] | None = None,
) -> dict:
    """T-CORPUS-4: zero train/test overlap on all three axes.

    Regenerates split membership from the corpus manifest (lazy
    ``flygpt.corpus.splits_from_manifest`` when available, else an
    injected ``split_fn``) and asserts, on the actual trials tables:

    - families are atomic (no family_id in two split labels), and every
      ``stimulus_holdout`` family is outside ``train``;
    - held-out cell types are never primary-stimulated targets in train
      (drive-node set intersected with the node->type map);
    - held-out regions likewise (node->region map).

    The recorded ``splits`` block may hold each axis as a flat list or
    as the nested ``{rule, seed, families|types|regions}`` block written
    by ``corpus.build_splits`` - both are normalized via
    ``_axis_members``.
    """
    test_id = "T-CORPUS-4"
    corpus_dir = Path(corpus_dir)
    manifest = _corpus_manifest(corpus_dir, corpus_manifest)
    splits = manifest.get("splits") or {}
    inputs = {"corpus_dir": str(corpus_dir), "splits": splits}
    trials = _trials_table(corpus_dir)
    if trials.height == 0:
        return _skipped(results_dir, test_id, f"no trials tables under {corpus_dir}")
    if node_type is None:
        node_type = manifest.get("node_type")
    if node_region is None:
        node_region = manifest.get("node_region")
    node_type = _load_node_map(node_type)
    node_region = _load_node_map(node_region)

    checks: dict[str, Any] = {"regeneration": None, "axes": {}}
    problems: list[str] = []

    if split_fn is None:
        try:
            from flygpt.corpus import splits_from_manifest as split_fn
        except Exception:
            split_fn = None
    if split_fn is not None:
        try:
            try:
                regen = split_fn(manifest)
            except TypeError:
                regen = split_fn(manifest, bundle, family_ids=family_ids)
        except Exception as exc:
            regen = None
            # Regeneration needs the bundle's node->type/region maps. When
            # it cannot run, the sub-check is NA unless the manifest
            # *claims* holdouts we then cannot verify - fail closed there.
            checks["regeneration"] = {"skipped": str(exc)}
            if any(_axis_members(splits, axis) for axis in _SPLIT_AXES):
                problems.append(f"split regeneration raised: {exc}")
        if regen is not None:
            # Only axes the manifest actually declares get compared: a
            # scope-limited corpus (pilot, subset) records no axis
            # holdouts, so regenerating them would produce phantom
            # "mismatches". Axes absent from the manifest are NA, not
            # violations - the axis hygiene checks below still run on
            # the real trials table.
            declared = [a for a in _SPLIT_AXES if _axis_members(splits, a)]
            if not declared:
                checks["regeneration"] = {
                    "skipped": "no axis holdouts declared in manifest"
                }
            else:
                mismatch = False
                for axis in declared:
                    recorded = sorted(_axis_members(splits, axis))
                    regenerated = sorted(_axis_members(regen, axis))
                    if recorded != regenerated:
                        mismatch = True
                        problems.append(f"splits.{axis} regeneration mismatch")
                        checks["regeneration"] = {
                            "axis": axis,
                            "recorded": recorded,
                            "regenerated": regenerated,
                        }
                if not mismatch:
                    checks["regeneration"] = {"ok": True}

    fam_split: dict[str, set] = {}
    train_targets_type: set[str] = set()
    train_targets_region: set[str] = set()
    holdout_fam = set(_axis_members(splits, "stimulus_holdout"))
    holdout_type = set(_axis_members(splits, "celltype_holdout"))
    holdout_region = set(_axis_members(splits, "region_holdout"))
    fam_train = fam_test = 0
    for row in trials.iter_rows(named=True):
        fam = row.get("family_id") or ""
        split = row.get("split") or ""
        fam_split.setdefault(fam, set()).add(split)
        if split == "train" and (node_type is not None or node_region is not None):
            for n in _drive_nodes_of(row.get("program")):
                if node_type is not None and n < node_type.size:
                    train_targets_type.add(str(node_type[n]))
                if node_region is not None and n < node_region.size:
                    train_targets_region.add(str(node_region[n]))

    non_atomic = {f: sorted(s) for f, s in fam_split.items() if len(s) > 1}
    if non_atomic:
        problems.append(f"families spanning multiple splits: {sorted(non_atomic)}")
    leaked_fam = {f for f in holdout_fam if "train" in fam_split.get(f, set())}
    if leaked_fam:
        problems.append(f"holdout families present in train: {sorted(leaked_fam)}")
    fam_train = len({f for f, s in fam_split.items() if s == {"train"}})
    fam_test = len({f for f, s in fam_split.items() if "test" in s or "eval" in s})

    axes: dict[str, Any] = {
        "families": {
            "checked": True,
            "non_atomic": non_atomic,
            "holdout_in_train": sorted(leaked_fam),
        }
    }
    if node_type is not None:
        leaked_types = sorted((train_targets_type & holdout_type) - {""})
        axes["cell_types"] = {"checked": True, "holdout_driven_in_train": leaked_types}
        if leaked_types:
            problems.append(f"holdout cell types driven in train: {leaked_types}")
    else:
        axes["cell_types"] = {"checked": False, "reason": "node->type map absent"}
        if holdout_type:
            problems.append("celltype axis unchecked: node->type map absent")
    if node_region is not None:
        leaked_regions = sorted((train_targets_region & holdout_region) - {""})
        axes["regions"] = {"checked": True, "holdout_driven_in_train": leaked_regions}
        if leaked_regions:
            problems.append(f"holdout regions driven in train: {leaked_regions}")
    else:
        axes["regions"] = {"checked": False, "reason": "node->region map absent"}
        if holdout_region:
            problems.append("region axis unchecked: node->region map absent")

    checks["axes"] = axes
    checks["problems"] = problems
    checks["counts"] = {"train_families": fam_train, "test_or_eval_families": fam_test}
    return write_result(
        results_dir,
        test_id,
        checks=checks,
        inputs=inputs,
        metrics={"n_problems": len(problems)},
        passed=bool(len(problems) == 0),
    )



def _load_node_map(value: Any, n_nodes: int | None = None) -> np.ndarray | None:
    """node_type/node_region as array, dict {idx: label}, or manifest list."""
    if value is None:
        return None
    if isinstance(value, dict):
        size = n_nodes or (max(int(k) for k in value) + 1 if value else 0)
        arr = np.full(size, "", dtype=object)
        for k, v in value.items():
            arr[int(k)] = v
        return arr.astype(str)
    return np.asarray(value).astype(str)


def _corpus_manifest(corpus_dir: Path, path: Path | None) -> dict:
    cand = Path(path) if path else corpus_dir / "corpus.manifest.json"
    if cand.exists():
        return json.loads(cand.read_text())
    for mpath in sorted(corpus_dir.glob("*.manifest.json")):
        try:
            m = json.loads(mpath.read_text())
        except Exception:
            continue
        if "splits" in m or "types" in m:
            return m
    return {}


def _corpus_events(corpus_dir: Path) -> tuple[np.ndarray, np.ndarray]:
    """Concatenated (trial_id, neuron_idx) event columns across shards."""
    trials_l, nodes_l = [], []
    for s in _shard_files(corpus_dir):
        if not s["events"].exists():
            continue
        ev = pl.read_parquet(s["events"], columns=[EVENT_TRIAL, EVENT_NODE])
        trials_l.append(ev[EVENT_TRIAL].to_numpy())
        nodes_l.append(ev[EVENT_NODE].to_numpy())
    if not trials_l:
        return np.empty(0, dtype=np.int64), np.empty(0, dtype=np.int64)
    return np.concatenate(trials_l), np.concatenate(nodes_l)


def run_t_corpus_3(
    corpus_dir: Path,
    results_dir: Path,
    *,
    manifest_types: list[str] | None = None,
    node_type: Any = None,
    corpus_manifest: Path | None = None,
    bundle=None,
    floor_driven: float = DRIVEN_FLOOR,
    floor_robust: float = ROBUST_FLOOR,
) -> dict:
    """T-CORPUS-3: >= 90% manifest types driven, >= 75% robustly driven.

    The denominator comes from the corpus manifest (``types`` list) -
    never hardcoded. ``node_type`` (or the manifest's own node_type map,
    or a ``bundle``) maps neuron_idx -> type; untyped nodes' events are
    counted but cannot drive a manifest type.
    """
    test_id = "T-CORPUS-3"
    corpus_dir = Path(corpus_dir)
    manifest = _corpus_manifest(corpus_dir, corpus_manifest)
    # Denominator precedence: the corpus's own declared driven-type scope
    # (corpus.manifest.json `types`) wins over an injected brain manifest -
    # a scoped corpus (pilot, subset) is judged against what it declared.
    if manifest.get("types") is not None:
        manifest_types = manifest["types"]
    if manifest_types is None and bundle is not None:
        manifest_types = bundle.manifest_types
    if node_type is None:
        node_type = manifest.get("node_type")
    if node_type is None and bundle is not None:
        node_type = bundle.type_array()
    node_type = _load_node_map(node_type)
    inputs = {"corpus_dir": str(corpus_dir), "floors": {"driven": floor_driven, "robust": floor_robust}}
    if manifest_types is None:
        return _skipped(
            results_dir, test_id, "manifest type denominator absent (never hardcoded)", inputs=inputs
        )
    if node_type is None:
        return _skipped(results_dir, test_id, "node->type map unavailable", inputs=inputs)
    ev_trial, ev_node = _corpus_events(corpus_dir)
    cov = common.coverage_by_type(ev_trial, ev_node, node_type, manifest_types)
    checks = {
        **{k: cov[k] for k in ("n_types", "n_driven", "n_robust", "driven_fraction", "robust_fraction")},
        "floors": {"driven": floor_driven, "robust": floor_robust},
        "per_type": cov["per_type"],
    }
    return write_result(
        results_dir,
        test_id,
        checks=checks,
        inputs=inputs,
        metrics={
            "driven_fraction": cov["driven_fraction"],
            "robust_fraction": cov["robust_fraction"],
        },
        passed=bool(cov["driven_fraction"] >= floor_driven and cov["robust_fraction"] >= floor_robust),
    )



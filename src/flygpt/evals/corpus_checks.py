DRIVEN_FLOOR = 0.90   # T-CORPUS-3 primary floor (EVAL 1.8 + section 5)
ROBUST_FLOOR = 0.75   # T-CORPUS-3 secondary floor

_EVENT_DTYPES = {
    EVENT_TRIAL: (pl.UInt64,),
    EVENT_STEP: (pl.UInt32, pl.Int32, pl.Int64),
    EVENT_NODE: (pl.UInt32, pl.Int32, pl.Int64),
}



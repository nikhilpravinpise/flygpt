def _split_field_sets(corpus_dir: Path) -> tuple[dict, list[str], list[str]]:
    """Per-split {slice, dt} sets plus label (T5) and dt (T7) problems."""
    per_split: dict[str, dict] = {}
    label_problems: list[str] = []
    dt_problems: list[str] = []
    for s in _shard_files(corpus_dir):
        m = s["manifest"]
        base = s["base"]
        if not s["trials"].exists():
            label_problems.append(f"{base}: trials parquet missing")
            dt_problems.append(f"{base}: trials parquet missing")
            continue
        trials = pl.read_parquet(s["trials"])
        for col in ("slice", "split"):
            if col not in trials.columns:
                label_problems.append(f"{base}: trials missing column {col}")
        if "dt" not in trials.columns:
            dt_problems.append(f"{base}: trials missing column dt")
        if not m.get("slice"):
            label_problems.append(f"{base}: manifest.slice absent")
        if m.get("dt") is None:
            dt_problems.append(f"{base}: manifest.dt absent")
        if "split" not in trials.columns:
            continue
        for row in trials.iter_rows(named=True):
            split = row.get("split") or "<none>"
            entry = per_split.setdefault(split, {"slices": set(), "dts": set(), "shards": set()})
            sl = row.get("slice") if "slice" in trials.columns else "<missing>"
            entry["slices"].add(sl if sl else "<missing>")
            if row.get("dt") is not None:
                entry["dts"].add(float(row["dt"]))
            else:
                entry["dts"].add(None)
            entry["shards"].add(base)
            if not sl or sl == "<missing>":
                label_problems.append(f"{base}: trial {row.get('trial_id')} slice label empty")
            if row.get("dt") is None:
                dt_problems.append(f"{base}: trial {row.get('trial_id')} dt null")
    return per_split, label_problems, dt_problems


def run_t_corpus_5(corpus_dir: Path, results_dir: Path) -> dict:
    """T-CORPUS-5: 100% of convention-variant shards labeled; zero
    convention slices mixed within a split."""
    test_id = "T-CORPUS-5"
    corpus_dir = Path(corpus_dir)
    per_split, problems, _ = _split_field_sets(corpus_dir)
    mixed = {
        split: sorted(str(s) for s in v["slices"])
        for split, v in per_split.items()
        if len(v["slices"]) > 1
    }
    for split in mixed:
        problems.append(f"split {split!r} mixes convention slices: {mixed[split]}")
    n_unlabeled = len(problems)
    return write_result(
        results_dir,
        test_id,
        checks={
            "per_split_slices": {k: sorted(str(s) for s in v["slices"]) for k, v in per_split.items()},
            "mixed_splits": mixed,
            "problems": problems,
        },
        inputs={"corpus_dir": str(corpus_dir)},
        metrics={"n_problems": n_unlabeled, "n_mixed_splits": len(mixed)},
        passed=bool(len(problems) == 0),
    )


def run_t_corpus_7(corpus_dir: Path, results_dir: Path) -> dict:
    """T-CORPUS-7: dt is a convention-slice axis - each slice carries
    exactly one dt corpus-wide (EVAL: "dt values disjoint between
    slices"), and every shard + trial row records dt."""
    test_id = "T-CORPUS-7"
    corpus_dir = Path(corpus_dir)
    per_split, _, dt_problems = _split_field_sets(corpus_dir)
    # Slice-keyed view: a slice straddling splits with two dts is a
    # convention mix even when each split is internally uniform.
    per_slice: dict[str, set] = {}
    slice_splits: dict[str, set] = {}
    for s in _shard_files(corpus_dir):
        if not s["trials"].exists():
            continue
        for row in pl.read_parquet(s["trials"]).iter_rows(named=True):
            sl = str(row.get("slice") or "<missing>")
            per_slice.setdefault(sl, set()).add(row.get("dt"))
            slice_splits.setdefault(sl, set()).add(str(row.get("split") or "<none>"))
    mixed_slices = {sl: sorted(v) for sl, v in per_slice.items() if len(v) > 1}
    mixed_splits = {
        split: sorted({d for sl in mixed_slices for d in per_slice[sl]})
        for sl in mixed_slices
        for split in slice_splits[sl]
    }
    for split in mixed_splits:
        dt_problems.append(f"split {split!r} mixes dt values: {mixed_splits[split]}")
    return write_result(
        results_dir,
        test_id,
        checks={
            "per_split_dts": {k: sorted(v["dts"], key=lambda x: (x is None, x)) for k,
                v in per_split.items()},
            "per_slice_dts": {k: sorted(float(x) for x in v if x is not None) for k, v in per_slice.items()},
            "mixed_dt_slices": mixed_slices,
            "mixed_dt_splits": mixed_splits,
            "problems": dt_problems,
        },
        inputs={"corpus_dir": str(corpus_dir)},
        metrics={"n_problems": len(dt_problems), "n_mixed_dt_splits": len(mixed_splits)},
        passed=bool(len(dt_problems) == 0),
    )


# ---------------------------------------------------------------------------
# T-CORPUS-6: regeneration determinism
# ---------------------------------------------------------------------------


def run_t_corpus_6(
    corpus_dir: Path,
    results_dir: Path,
    *,
    bundle=None,
    simulate_fn: Callable | None = None,
    cfg: Any = None,
    shard_id: str | None = None,
) -> dict:
    """T-CORPUS-6: regenerate a shard from manifest + seeds; compare.

    Each stored trial is re-simulated with its recorded ``program`` spec
    + ``seed``; the concatenated regenerated event table is compared to
    the stored one. CPU (numpy) shards must be bitwise-identical; other
    backends report the EVAL 1.4 agreement metrics against the same-GPU
    tolerance. Skips with reason when no sim is available.
    """
    test_id = "T-CORPUS-6"
    corpus_dir = Path(corpus_dir)
    sim = _require_sim(simulate_fn)
    inputs = {"corpus_dir": str(corpus_dir), "shard_id": shard_id}
    if sim is None:
        return _skipped(results_dir, test_id, "flygpt.sim_backend.simulate unavailable", inputs=inputs)
    shards = _shard_files(corpus_dir)
    if shard_id:
        shards = [s for s in shards if s["base"] == shard_id or s["manifest"].get("shard_id") == shard_id]
    if not shards:
        return _skipped(results_dir, test_id, "no matching shard found", inputs=inputs)
    s = shards[0]
    if not s["events"].exists() or not s["trials"].exists():
        return _skipped(results_dir, test_id, "shard files incomplete", inputs=inputs)

    stored = pl.read_parquet(s["events"]).sort([EVENT_TRIAL, EVENT_STEP, EVENT_NODE])
    trials = pl.read_parquet(s["trials"])
    n_nodes = int(bundle.n_nodes) if bundle is not None else int(
        stored[EVENT_NODE].max() + 1 if stored.height else 0
    )
    cfg = cfg if cfg is not None else (s["manifest"].get("sim_cfg") or {})
    dt = float(s["manifest"].get("dt") or _cfg_get(cfg, "dt", 0.02))
    backend = str(s["manifest"].get("backend") or _cfg_get(cfg, "backend", "numpy"))

    regen_rows = []
    n_regened = 0
    for row in trials.iter_rows(named=True):
        tid = int(row["trial_id"])
        prog = row.get("program")
        prog = json.loads(prog) if isinstance(prog, str) else (prog or {})
        prog.setdefault("dt", dt)
        prog.setdefault("n_steps", int(row.get("n_steps") or 0))
        seed = int(row.get("seed") if row.get("seed") is not None else seed_from_config(prog))
        res = _call_sim(sim, bundle, prog, cfg, seed)
        steps, nodes, _ = _events_of(res)
        regen_rows.append(
            np.stack(
                [np.full(steps.size, tid, dtype=np.uint64), steps.astype(np.uint32), nodes.astype(np.uint32)],
                axis=1,
            )
            if steps.size
            else np.empty((0, 3), dtype=np.uint64)
        )
        n_regened += 1
    regen = np.concatenate(regen_rows) if regen_rows else np.empty((0, 3), dtype=np.uint64)
    order = np.lexsort((regen[:, 2], regen[:, 1], regen[:, 0])) if regen.size else np.arange(0)
    regen = regen[order]
    stored_arr = stored.to_numpy().astype(np.int64)
    bitwise = bool(stored_arr.shape == regen.shape and (stored_arr == regen.astype(np.int64)).all())

    agreement = None
    if not bitwise:
        per_trial = []
        for tid in np.unique(stored_arr[:, 0]):
            st = stored_arr[stored_arr[:, 0] == tid]
            rg = regen[regen[:, 0] == tid]
            n_steps = int(trials.filter(pl.col("trial_id") == tid)["n_steps"][0])
            per_trial.append(
                common.spike_agreement(
                    (st[:, 1], st[:, 2]), (rg[:, 1], rg[:, 2]), n_nodes, n_steps
                )
            )
        agreement = (
            {
                k: float(np.mean([a[k] for a in per_trial]))
                for k in per_trial[0]
                if isinstance(per_trial[0][k], float)
            }
            if per_trial
            else None
        )

    tol = {"event": 0.995, "pm1_step": 0.999, "rate_pearson": 0.999}
    within_tol = bool(
        agreement
        and agreement["event_agreement"] >= tol["event"]
        and agreement["pm1_step_agreement"] >= tol["pm1_step"]
        and agreement["rate_pearson"] >= tol["rate_pearson"]
    )
    passed = bitwise if backend == "numpy" else within_tol
    return write_result(
        results_dir,
        test_id,
        checks={
            "shard": s["base"],
            "backend": backend,
            "n_trials_regenerated": n_regened,
            "n_events_stored": int(stored_arr.shape[0]),
            "n_events_regenerated": int(regen.shape[0]),
            "bitwise_identical": bitwise,
            "agreement": agreement,
            "tolerance": tol if backend != "numpy" else None,
        },
        inputs=inputs,
        metrics={"bitwise_identical": bitwise},
        passed=bool(passed),
    )



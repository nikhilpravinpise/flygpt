def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="T-CORPUS-1..7 corpus integrity checks")
    parser.add_argument("--corpus-dir", type=Path, default=Path("data/corpus"))
    parser.add_argument("--graph-dir", type=Path, default=Path("data/graph"))
    parser.add_argument("--results-dir", type=Path, default=Path("results"))
    args = parser.parse_args(argv)

    corpus_dir = args.corpus_dir
    if not corpus_dir.exists():
        for tid in (f"T-CORPUS-{i}" for i in range(1, 8)):
            _skipped(args.results_dir, tid, f"corpus_dir absent: {corpus_dir}")
        return 0
    bundle = None
    if (args.graph_dir / "nodes.parquet").exists():
        from flygpt.schema import load_graph_bundle

        bundle = load_graph_bundle(args.graph_dir)
    run_t_corpus_1(corpus_dir, args.results_dir)
    run_t_corpus_2(corpus_dir, args.results_dir)
    run_t_corpus_3(corpus_dir, args.results_dir, bundle=bundle)
    run_t_corpus_4(corpus_dir, args.results_dir)
    run_t_corpus_5(corpus_dir, args.results_dir)
    run_t_corpus_6(corpus_dir, args.results_dir, bundle=bundle)
    run_t_corpus_7(corpus_dir, args.results_dir)
    return 0


if __name__ == "__main__":
    sys.exit(main())

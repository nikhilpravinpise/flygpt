_NON_SHARD_MANIFESTS = {"corpus", "vocab", "stimuli", "library", "index"}


def _shard_files(corpus_dir: Path) -> list[dict]:
    """Shard triples under ``corpus_dir`` keyed on ``*.manifest.json``.

    Supports both ``<sid>.manifest.json`` + ``events-<sid>.parquet`` /
    ``trials-<sid>.parquet`` (flygpt.corpus.write_shard convention) and
    the flat ``<sid>.events.parquet`` / ``<sid>.trials.parquet`` layout.
    """
    shards = []
    for mpath in sorted(corpus_dir.glob("*.manifest.json")):
        base = mpath.name[: -len(".manifest.json")]
        if base in _NON_SHARD_MANIFESTS:
            continue
        try:
            manifest = json.loads(mpath.read_text())
        except Exception:
            manifest = {}
        sid = str(manifest.get("shard_id") or base)
        candidates = {
            "events": [corpus_dir / f"events-{sid}.parquet", corpus_dir / f"{sid}.events.parquet"],
            "trials": [corpus_dir / f"trials-{sid}.parquet", corpus_dir / f"{sid}.trials.parquet"],
        }
        paths = {
            kind: next((p for p in cands if p.exists()), cands[0])
            for kind, cands in candidates.items()
        }
        if paths["events"].exists() or paths["trials"].exists() or "shard_id" in manifest:
            shards.append(
                {
                    "base": sid,
                    "manifest_path": mpath,
                    "manifest": manifest,
                    "events": paths["events"],
                    "trials": paths["trials"],
                }
            )
    return shards


def validate_shard(
    events_path: Path, trials_path: Path, manifest_path: Path | None = None
) -> dict:
    """Local shard schema validation (T-CORPUS-1).

    Checks the events schema (column names + dtypes + sortedness by
    trial,step,node), the trials schema (all TRIAL_COLUMNS present,
    trial_id unique), and that every event's trial_id is registered in
    the trials table. Used when ``flygpt.corpus.validate_shard`` is not
    importable - identical contract.
    """
    problems: list[str] = []
    if not events_path.exists():
        return {"ok": False, "problems": ["events parquet missing"]}
    events = pl.read_parquet(events_path)
    for col, dtypes in _EVENT_DTYPES.items():
        if col not in events.columns:
            problems.append(f"events missing column {col}")
        elif events[col].dtype not in dtypes:
            problems.append(f"events column {col} dtype {events[col].dtype} not in {dtypes}")
    if not problems and events.height:
        key = events.select([EVENT_TRIAL, EVENT_STEP, EVENT_NODE])
        if not key.equals(key.sort([EVENT_TRIAL, EVENT_STEP, EVENT_NODE])):
            problems.append("events not sorted by (trial_id, step, neuron_idx)")

    if not trials_path.exists():
        problems.append("trials parquet missing")
    else:
        trials = pl.read_parquet(trials_path)
        for col in TRIAL_COLUMNS:
            if col not in trials.columns:
                problems.append(f"trials missing column {col}")
        if "trial_id" in trials.columns and not trials["trial_id"].is_unique().all():
            problems.append("trials trial_id not unique")
        if not problems and events.height and trials.height:
            known = set(trials["trial_id"].to_list())
            stray = set(events[EVENT_TRIAL].unique().to_list()) - known
            if stray:
                problems.append(f"{len(stray)} event trial_ids absent from trials table")
    if manifest_path is not None and not Path(manifest_path).exists():
        problems.append("manifest missing")
    return {"ok": not problems, "problems": problems}


def run_t_corpus_1(
    corpus_dir: Path,
    results_dir: Path,
    *,
    validate_fn: Callable | None = None,
) -> dict:
    """T-CORPUS-1: 100% of shards validate the declared schema.

    Uses the local schema-scoped ``validate_shard`` (columns, dtypes,
    sortedness, trial registration) - manifest provenance and slice
    purity are T-2/T-5 territory, so failures here mean schema only.
    """
    test_id = "T-CORPUS-1"
    corpus_dir = Path(corpus_dir)
    if validate_fn is None:
        # T-1 scope is the shard SCHEMA (columns/dtypes/sortedness/trial
        # registration). corpus.validate_shard also covers manifest
        # provenance + slice purity - those belong to T-2/T-5 and would
        # make T-1 fail for the wrong reason, so the local validator is
        # the default here.
        validate_fn = validate_shard
    shards = _shard_files(corpus_dir)
    if not shards:
        return _skipped(results_dir, test_id, f"no shards under {corpus_dir}")
    per_shard = {}
    for s in shards:
        try:
            verdict = validate_fn(s["events"], s["trials"], s["manifest_path"])
        except TypeError:
            verdict = validate_fn(s["events"], s["trials"])
        per_shard[s["base"]] = verdict if isinstance(verdict, dict) else {"ok": bool(verdict)}
    bad = {k: v for k, v in per_shard.items() if not v.get("ok")}
    return write_result(
        results_dir,
        test_id,
        checks={"n_shards": len(shards), "per_shard": per_shard, "invalid": bad},
        inputs={"corpus_dir": str(corpus_dir)},
        metrics={"n_invalid": len(bad)},
        passed=bool(len(bad) == 0),
    )



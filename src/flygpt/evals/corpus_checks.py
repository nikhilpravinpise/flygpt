def run_t_corpus_2(corpus_dir: Path, results_dir: Path) -> dict:
    """T-CORPUS-2: every shard manifest resolves to real source hashes.

    Requires per manifest: ``code.git_sha`` non-empty, ``graph.sha256``
    non-empty, and recorded sha256 for both shard files recomputed here
    and matched exactly - fail closed on any mismatch.
    """
    test_id = "T-CORPUS-2"
    corpus_dir = Path(corpus_dir)
    shards = _shard_files(corpus_dir)
    if not shards:
        return _skipped(results_dir, test_id, f"no shards under {corpus_dir}")
    per_shard = {}
    n_bad = 0
    for s in shards:
        m = s["manifest"]
        problems = []
        if not m:
            problems.append("manifest unreadable")
        git = (m.get("code") or {}).get("git_sha") or (m.get("code") or {}).get("sha")
        if not git:
            problems.append("code.git_sha absent")
        if not ((m.get("graph") or {}).get("sha256")):
            problems.append("graph.sha256 absent")
        files = m.get("files") or {}
        for kind, path in (("events", s["events"]), ("trials", s["trials"])):
            entry = files.get(kind) or {}
            # write_shard records the events hash at top level as
            # ``shard_sha256``; the flat layout uses files.<kind>.sha256.
            recorded = entry.get("sha256") or m.get(
                "shard_sha256" if kind == "events" else f"{kind}_sha256"
            )
            if not recorded:
                problems.append(f"{kind} sha256 absent from manifest")
                continue
            if not path.exists():
                problems.append(f"{kind} file missing: {path.name}")
                continue
            actual = sha256_file(path)
            if actual != recorded:
                problems.append(f"{kind} sha256 mismatch")
            if entry.get("name") and entry["name"] != path.name:
                problems.append(f"{kind} name mismatch: {entry['name']} != {path.name}")
        per_shard[s["base"]] = {"ok": not problems, "problems": problems}
        n_bad += int(bool(problems))
    return write_result(
        results_dir,
        test_id,
        checks={"n_shards": len(shards), "per_shard": per_shard},
        inputs={"corpus_dir": str(corpus_dir)},
        metrics={"n_unresolved": n_bad},
        passed=bool(n_bad == 0),
    )


